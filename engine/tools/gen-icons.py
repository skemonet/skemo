#!/usr/bin/env python3 -I
"""Generate crates/engine/src/icons/data.rs from an extracted Lucide release (ISC licence).

    python3 -I tools/gen-icons.py <lucide-dir> <version> <archive-sha256> [subset.txt]

<lucide-dir> holds `icons/*.svg` and `icons/*.json` (the release archive, extracted into its own
empty directory: untrusted data, only read here). Standard library only.
Each icon becomes (name, inner SVG markup, search tags), sorted by name.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ALLOWED = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
ATTRS = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points"}
NUM = re.compile(r"^[A-Za-z0-9 .,\-+eE]+$")


def inner(path: Path) -> str:
    root = ET.parse(path).getroot()
    out = []
    for el in root:
        tag = el.tag.split("}")[-1]
        if tag not in ALLOWED:
            raise SystemExit(f"{path.name}: unexpected element {tag}")
        parts = []
        for k, v in el.attrib.items():
            if (k, v) == ("fill", "currentColor"):  # the dots of a few icons
                parts.append(f'{k}="{v}"')
                continue
            if k not in ATTRS or not NUM.match(v):
                raise SystemExit(f"{path.name}: unexpected attribute {k}={v!r}")
            parts.append(f'{k}="{v}"')
        out.append(f"<{tag} {' '.join(parts)}/>")
    return "".join(out)


def main() -> None:
    src, version, sha = Path(sys.argv[1]) / "icons", sys.argv[2], sys.argv[3]
    keep = None
    if len(sys.argv) > 4:
        keep = {l.strip() for l in Path(sys.argv[4]).read_text().splitlines() if l.strip() and not l.startswith("#")}
    rows = []
    for svg in sorted(src.glob("*.svg")):
        name = svg.stem
        if keep is not None and name not in keep:
            continue
        meta = json.loads(svg.with_suffix(".json").read_text())
        rows.append((name, inner(svg), " ".join(meta.get("tags", []))))
    rows.sort(key=lambda r: r[0])
    lines = [
        f"// @generated by tools/gen-icons.py from Lucide {version} (ISC, see assets/icons/LICENSE-lucide.txt).",
        f"// Archive SHA-256: {sha}. Do not edit by hand.",
        "",
        "/// `(name, inner SVG markup of the 24x24 icon, search tags)`, sorted by name.",
        f"pub(super) static ICONS: [(&str, &str, &str); {len(rows)}] = [",
    ]
    for n, body, tags in rows:
        lines.append(f'    ("{n}", "{body.replace(chr(34), chr(92) + chr(34))}", "{tags}"),')
    lines.append("];")
    Path("crates/engine/src/icons/data.rs").write_text("\n".join(lines) + "\n")
    print(len(rows), "icons")


main()
